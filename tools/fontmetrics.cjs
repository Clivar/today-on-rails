// Generates watchface/src/ui/metrics.js: advance widths (in em units) for printable ASCII
// plus a few symbols, read straight from the TTF files, so the watch code can lay
// out text runs without measuring on the device.
// Usage: node tools/fontmetrics.cjs
const fs = require('fs')
const path = require('path')

const ROOT = path.join(__dirname, '..')
const FONTS = {
  medium: 'Barlow-Medium.ttf',
  semibold: 'Barlow-SemiBold.ttf',
  bold: 'Barlow-Bold.ttf',
  digits: 'BarlowCondensed-SemiBold.ttf',
}
const EXTRA = '·°…'

function tables(buf) {
  const n = buf.readUInt16BE(4)
  const t = {}
  for (let i = 0; i < n; i++) {
    const o = 12 + i * 16
    t[buf.toString('latin1', o, o + 4)] = buf.readUInt32BE(o + 8)
  }
  return t
}

// cmap format 4 (BMP) lookup
function cmapLookup(buf, t) {
  const cmap = t.cmap
  const n = buf.readUInt16BE(cmap + 2)
  let sub = -1
  for (let i = 0; i < n; i++) {
    const o = cmap + 4 + i * 8
    const pid = buf.readUInt16BE(o), eid = buf.readUInt16BE(o + 2)
    if (pid === 3 && eid === 1) sub = cmap + buf.readUInt32BE(o + 4)
  }
  if (sub < 0 || buf.readUInt16BE(sub) !== 4) throw new Error('no cmap format 4')
  const segX2 = buf.readUInt16BE(sub + 6)
  const ends = sub + 14, starts = ends + segX2 + 2, deltas = starts + segX2, ranges = deltas + segX2
  return (code) => {
    for (let i = 0; i < segX2 / 2; i++) {
      const end = buf.readUInt16BE(ends + i * 2)
      if (code > end) continue
      const start = buf.readUInt16BE(starts + i * 2)
      if (code < start) return 0
      const delta = buf.readInt16BE(deltas + i * 2)
      const ro = buf.readUInt16BE(ranges + i * 2)
      if (ro === 0) return (code + delta) & 0xffff
      const g = buf.readUInt16BE(ranges + i * 2 + ro + (code - start) * 2)
      return g === 0 ? 0 : (g + delta) & 0xffff
    }
    return 0
  }
}

function metrics(file) {
  const buf = fs.readFileSync(path.join(ROOT, 'fonts', file))
  const t = tables(buf)
  const upm = buf.readUInt16BE(t.head + 18)
  const ascender = buf.readInt16BE(t.hhea + 4)
  const descender = buf.readInt16BE(t.hhea + 6)
  const numH = buf.readUInt16BE(t.hhea + 34)
  const glyph = cmapLookup(buf, t)
  const adv = (g) => buf.readUInt16BE(t.hmtx + Math.min(g, numH - 1) * 4)
  const widths = {}
  for (let c = 32; c < 127; c++) widths[String.fromCharCode(c)] = +(adv(glyph(c)) / upm).toFixed(4)
  for (const ch of EXTRA) widths[ch] = +(adv(glyph(ch.charCodeAt(0))) / upm).toFixed(4)
  return { ascender: +(ascender / upm).toFixed(4), descender: +(descender / upm).toFixed(4), widths }
}

const out = {}
for (const [k, f] of Object.entries(FONTS)) out[k] = metrics(f)
fs.writeFileSync(
  path.join(ROOT, 'watchface', 'src', 'ui', 'metrics.js'),
  '// Generated by tools/fontmetrics.cjs — do not edit\nexport const METRICS = ' + JSON.stringify(out) + '\n',
)
console.log('digits 0-9:', [...'0123456789:'].map((c) => out.digits.widths[c]).join(' '))
console.log('ascender/descender:', Object.entries(out).map(([k, v]) => `${k} ${v.ascender}/${v.descender}`).join(', '))
